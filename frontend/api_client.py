class BackendError(Exception):
    """Raised for any connection, HTTP or decoding problem."""


def _url(base_url: str, path: str) -> str:
    return base_url.rstrip("/") + path


def _request(method: str, base_url: str, path: str, json: dict | None = None):
    try:
        resp = requests.request(method, _url(base_url, path), json=json, timeout=TIMEOUT_S)
        resp.raise_for_status()
        return resp.json()
    except requests.exceptions.ConnectionError:
        raise BackendError(f"Cannot reach {base_url}. Is the FastAPI container running?")
    except requests.exceptions.Timeout:
        raise BackendError(f"{base_url} did not answer within {TIMEOUT_S} s.")
    except requests.exceptions.HTTPError as e:
        raise BackendError(f"{path} returned HTTP {e.response.status_code}: {e.response.text[:200]}")
    except ValueError:
        raise BackendError(f"{path} did not return JSON.")


# --- One function per existing endpoint --------------------------------------------
def health_check(base_url: str = DEFAULT_BASE_URL) -> dict:
    return _request("GET", base_url, ENDPOINTS["health"])


def predict_cwru(payload: dict, base_url: str = DEFAULT_BASE_URL) -> dict:
    return _request("POST", base_url, ENDPOINTS["cwru"], json=payload)


def predict_ims(payload: dict, base_url: str = DEFAULT_BASE_URL) -> dict:
    return _request("POST", base_url, ENDPOINTS["ims"], json=payload)


def predict_cmapss(payload: dict, base_url: str = DEFAULT_BASE_URL) -> dict:
    return _request("POST", base_url, ENDPOINTS["cmapss"], json=payload)


def send_sensor_data(payload: dict, base_url: str = DEFAULT_BASE_URL) -> dict:
    """Submit an MPU6050 reading. Ingestion/diagnostic only, NOT an IMS prediction path."""
    return _request("POST", base_url, ENDPOINTS["sensor"], json=payload)


def get_latest_sensor(base_url: str = DEFAULT_BASE_URL) -> dict:
    """Fetch the backend's cached most-recent /sensor-data reading (display
    only -- see api/app.py's GET /sensor-data/latest)."""
    return _request("GET", base_url, "/sensor-data/latest")


def get_openapi_schema(base_url: str = DEFAULT_BASE_URL) -> dict:
    return _request("GET", base_url, "/openapi.json")


# --- Mapping backend responses to the dashboard --------------------------------------
def _run_model(name: str, predict_fn, base_url: str) -> dict:
    payload = SAMPLE_PAYLOADS[name]
    if payload is None:
        return {
            "available": False,
            "reason": f"No real sample payload supplied yet for '{name}'. "
                      f"Add it to SAMPLE_PAYLOADS in api_client.py once the "
                      f"real data file exists (see tools/sample_payloads/).",
        }
    try:
        resp = predict_fn(payload, base_url)
        values = RESPONSE_TRANSFORMS[name](resp)
    except BackendError as e:
        return {"available": False, "reason": str(e)}
    except (KeyError, TypeError, ValueError) as e:
        return {"available": False, "reason": f"Response from '{name}' did not match the expected shape: {e}"}
    return {"available": True, **values}


def _fetch_sensor_section(base_url: str) -> dict:
    """Build the dashboard's 'sensor' section from the live cache, matching
    mock_data's shape exactly so app.py's render_sensors() needs no changes."""
    try:
        resp = get_latest_sensor(base_url)
    except BackendError as e:
        return {
            "available": False, "latest": None,
            "history": pd.DataFrame(columns=["timestamp", "ax", "ay", "az", "rms"]),
            "note": str(e),
        }

    if not resp.get("available"):
        return {
            "available": False, "latest": None,
            "history": pd.DataFrame(columns=["timestamp", "ax", "ay", "az", "rms"]),
            "note": resp.get("reason", "No live sensor reading yet."),
        }

    latest_raw = resp["latest"]
    latest = {
        "ax": latest_raw["ax"], "ay": latest_raw["ay"], "az": latest_raw["az"],
        "rms": latest_raw["rms"],
        "sampling_rate_hz": latest_raw["sampling_rate_hz"],
        # The ESP32 sends a UTC timestamp (e.g. "...Z"), which pandas parses
        # as timezone-AWARE. utils.fmt_age() compares this against
        # datetime.now() (timezone-NAIVE), so the tz info must be dropped
        # here or the subtraction raises a TypeError. Only relative "N
        # seconds ago" display precision is needed, not real tz correctness.
        "timestamp": pd.to_datetime(latest_raw["timestamp"], utc=True).tz_localize(None).to_pydatetime(),
    }

    history = pd.DataFrame(resp.get("history") or [])
    if not history.empty:
        # Same tz-awareness fix as the single "latest" reading above.
        history["timestamp"] = pd.to_datetime(history["timestamp"], utc=True).dt.tz_localize(None)
        history = history[["timestamp", "ax", "ay", "az", "rms"]]
    else:
        history = pd.DataFrame(columns=["timestamp", "ax", "ay", "az", "rms"])

    return {"available": True, "latest": latest, "history": history, "note": None}


def get_backend_dashboard_data(base_url: str, machine_id: str) -> dict:
    """Same structure as mock_data.generate_mock_dashboard_data(), filled from FastAPI."""
    try:
        health = health_check(base_url)
        backend = ("Online", "GET /health answered")
        connection = ("Connected", base_url)
    except BackendError as e:
        health = None
        backend = ("Unreachable", str(e))
        connection = ("Disconnected", base_url)

    if health is not None:
        cwru = _run_model("cwru", predict_cwru, base_url)
        ims = _run_model("ims", predict_ims, base_url)
        cmapss = _run_model("cmapss", predict_cmapss, base_url)
        sensor = _fetch_sensor_section(base_url)
    else:
        off = {"available": False, "reason": "Backend unreachable."}
        cwru, ims, cmapss = dict(off), dict(off), dict(off)
        sensor = {
            "available": False, "latest": None,
            "history": pd.DataFrame(columns=["timestamp", "ax", "ay", "az", "rms"]),
            "note": "Backend unreachable.",
        }
    ims.setdefault("history", pd.DataFrame(columns=["timestamp", "score"]))
    cmapss.setdefault("history", pd.DataFrame(columns=["cycle", "rul"]))
    cmapss.setdefault("unit", "cycles")

    def state(r):
        return ("Result received", "Prediction endpoint answered") if r["available"] else ("Not connected", r["reason"])

    return {
        "mode": "backend",
        "is_mock": False,
        "machine_id": machine_id,
        "generated_at": datetime.now(),
        "sensor": sensor,
        "cwru": cwru, "ims": ims, "cmapss": cmapss,
        "system": {
            "backend": backend,
            "models": {"cwru": state(cwru), "ims": state(ims), "cmapss": state(cmapss)},
            "data_source": f"FastAPI backend at {base_url}",
            "connection": connection,
            "raw_health": health,
        },
    }


# --- CLI: print the real schemas so nothing has to be guessed -------------------------
def _fields(schema: dict, components: dict) -> dict:
    if "$ref" in schema:
        schema = components.get(schema["$ref"].split("/")[-1], {})
    return {k: v.get("type", v.get("$ref", "?").split("/")[-1]) for k, v in schema.get("properties", {}).items()}


def describe_backend(base_url: str) -> None:
    spec = get_openapi_schema(base_url)
    components = spec.get("components", {}).get("schemas", {})
    print(f"Routes exposed by {base_url}:\n")
    for path, methods in spec.get("paths", {}).items():
        for method, op in methods.items():
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            ok = op.get("responses", {}).get("200", {}).get("content", {}).get("application/json", {}).get("schema")
            print(f"{method.upper():5} {path}")
            if body:
                print("   request :", _fields(body, components) or body)
            if ok:
                print("   response:", _fields(ok, components) or ok)


if __name__ == "__main__":
    url = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_BASE_URL
    try:
        describe_backend(url)
    except BackendError as e:
        print("Error:", e)
