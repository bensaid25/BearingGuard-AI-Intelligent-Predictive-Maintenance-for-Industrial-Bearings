"""Thin HTTP client for the existing FastAPI backend. It contains NO model logic.

SAMPLE_PAYLOADS holds a valid, REAL request body for each /predict/* endpoint --
never invented values. CWRU's sample comes from tests/test_cwru.py (the same
one already validated as a regression check). C-MAPSS and IMS still need their
real sample files (tools/sample_payloads/cmapss_payload_real.json and
ims_payload_real_*.json, generated by tools/generate_real_test_payloads.py) --
until those are supplied, those two stay disconnected honestly rather than
being filled with made-up feature vectors or signal data.

RESPONSE_TRANSFORMS replaces the old flat FIELD_MAP dotted-path lookup, because
the real responses aren't flat:
  - /predict/cwru returns `probabilities` as a dict keyed by class name, not a
    single `confidence` number -- the transform picks out the probability of
    the predicted class specifically.
  - /predict/ims returns `results` as an array (one entry per channel), not a
    single score -- the transform reports the most anomalous channel, since
    that's the one that should drive a machine-status dashboard.
  - /predict/cmapss is already flat (`predicted_rul`), so its transform is a
    trivial rename.

To (re)inspect the real schemas at any time:

    python frontend/api_client.py http://localhost:8000
"""
from __future__ import annotations

import json
import os
import sys
from datetime import datetime
from pathlib import Path
from typing import Callable

import pandas as pd
import requests

SAMPLE_PAYLOADS_DIR = Path(__file__).resolve().parent / "sample_payloads"


def _load_real_payload(filename: str) -> dict | None:
    """Load a real sample payload bundled alongside this file. Returns None
    (never invented data) if the file isn't present, so the dashboard falls
    back to an honest 'not connected' state instead of fabricating values."""
    path = SAMPLE_PAYLOADS_DIR / filename
    if not path.exists():
        return None
    with open(path) as f:
        return json.load(f)

DEFAULT_BASE_URL = os.getenv("FASTAPI_BASE_URL", "http://localhost:8000")
TIMEOUT_S = 5

ENDPOINTS = {
    "health": "/health",
    "cwru": "/predict/cwru",
    "ims": "/predict/ims",
    "cmapss": "/predict/cmapss",
    "sensor": "/sensor-data",
}

