# --- Response shape transforms (replaces flat dotted-path FIELD_MAP) ----------------
def _transform_cwru(resp: dict) -> dict:
    predicted = resp["predicted_class"]
    probabilities = resp.get("probabilities") or {}
    return {
        "fault_class": predicted,
        "confidence": probabilities.get(predicted),
    }


def _transform_ims(resp: dict) -> dict:
    results = resp.get("results") or []
    if not results:
        raise ValueError("IMS response had an empty 'results' array.")
    # Report the most anomalous channel -- the one that should drive a
    # machine-status dashboard, rather than an arbitrary first entry.
    worst = max(results, key=lambda r: r["anomaly_score"])
    return {
        "score": worst["anomaly_score"],
        "threshold": None,  # not returned by this endpoint; the Isolation
                            # Forest's decision boundary is internal to the
                            # model, so no numeric threshold is available to
                            # display. is_anomaly below is authoritative.
        "is_anomaly": worst["is_anomaly"],
    }


def _transform_cmapss(resp: dict) -> dict:
    return {"rul": resp["predicted_rul"]}


RESPONSE_TRANSFORMS: dict[str, Callable[[dict], dict]] = {
    "cwru": _transform_cwru,
    "ims": _transform_ims,
    "cmapss": _transform_cmapss,
}

